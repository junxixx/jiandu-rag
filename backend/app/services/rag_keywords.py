_PARTICLE_RE = re.compile(r"的|与|和|及|或|在|对|从|把|被|为|以|中|里|之|而|则|并|跟|同|向|到|至")
_RUN_RE = re.compile(r"[\u4e00-\u9fff]{2,}|[A-Za-z]{2,}(?:-[A-Za-z0-9]+)+|[A-Za-z][A-Za-z0-9_+]{2,}")
_PUNCT_RE = re.compile(r"[\s,，。！？?；;：:、\"'“”‘’（）()\[\]【】《》<>…·]+")
_CHAT_RE = re.compile(
    r"^(?:你好|您好|嗨|哈喽|哈罗|在吗|谢谢|多谢|感谢|再见|拜拜|你是谁|你能做什么|你会做什么|介绍一下你自己)"
    r"[呀啊呢吧吗！!。.\s]*$"
)
_SELF_RE = re.compile(r"此简|这枚|本简|本牍|这条简|这支简|当前这")


_CHAR_MAP = {a: b for a, b in _SIMP_TRAD}


def trad_variants(token: str) -> List[str]:
    """简体、全繁体，以及简牍里常见的简繁夹写。短词才展开夹写，避免组合爆炸。"""
    raw = (token or "").strip()
    if not raw:
        return []
    converted = raw.translate(_TO_TRAD)
    if len(raw) > 4:
        out = [raw]
        if converted != raw:
            out.append(converted)
        return out
    choices = []
    for ch in raw:
        alt = _CHAR_MAP.get(ch)
        choices.append((ch, alt) if alt and alt != ch else (ch,))
    out: List[str] = []

    def walk(i: int, acc: List[str]) -> None:
        if len(out) >= 16:
            return
        if i == len(choices):
            text = "".join(acc)
            if text not in out:
                out.append(text)
            return
        for ch in choices[i]:
            acc.append(ch)
            walk(i + 1, acc)
            acc.pop()

    walk(0, [])
    return out


def keyword_hit(keyword: str, text: str) -> bool:
    if not text:
        return False
    return any(v and v in text for v in trad_variants(keyword))


def extract_keywords(question: str, limit: int = 8) -> List[str]:
    text = _PUNCT_RE.sub(" ", question or "")
    for phrase in _STOP_PHRASES:
        text = text.replace(phrase, " ")
    found: List[str] = []
    seen: set[str] = set()

    def add(token: str) -> None:
        token = token.strip()
        if len(token) < 2 or token in seen:
            return
        if token in _STOP_PHRASES:
            return
        seen.add(token)
        found.append(token)

    for run in _RUN_RE.findall(text):
        if re.fullmatch(r"[A-Za-z0-9_+-]+", run):
            add(run)
            continue
        parts = [p for p in _PARTICLE_RE.split(run) if p]
        pieces = parts or [run]
        for piece in pieces:
            piece = piece.strip("了是呢啊吧吗的之")
            if 2 <= len(piece) <= 4:
                add(piece)
            elif len(piece) > 4:
                i = 0
                while i + 2 <= len(piece):
                    add(piece[i : i + 2])
                    i += 2
                if len(piece) % 2 == 1:
                    add(piece[-2:])
        if len(found) >= limit:
            break
    return found[:limit]


def is_chitchat(question: str) -> bool:
    q = re.sub(r"\s+", "", (question or "").strip())
    if not q:
        return True
    return bool(_CHAT_RE.match(q))


def asks_about_open_slip(question: str) -> bool:
    return bool(_SELF_RE.search(question or ""))
